/**
 * Generates lib/iconCatalog.ts from what is actually on disk.
 *
 * The palette has to offer every mark we vendored, and the list of those is
 * public/icons/ -- not a hand-kept array beside it. A hand-kept one drifts the
 * first time somebody adds an icon and forgets, and the failure is silent: the
 * file is there, nothing offers it, and it looks like the icon was never
 * fetched.
 *
 *   node scripts/build-icon-catalog.mjs
 *
 * Re-run after scripts/fetch_aws_icons.py or any hand-added icon.
 */

